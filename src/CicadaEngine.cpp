#include "CicadaEngine.h"

constexpr uint32_t WIDTH  = 800;
constexpr uint32_t HEIGHT = 600;

//==========================================================================================================================================================
//==========================================================================================================================================================
CicadaEngine::CicadaEngine() {}

//==========================================================================================================================================================
//==========================================================================================================================================================
void CicadaEngine::run() {
    initWindow();
    initVulkan();
    mainLoop();
    cleanup();
}

//==========================================================================================================================================================
//==========================================================================================================================================================
void CicadaEngine::initWindow() {
    glfwInit();                                     // Init API
    glfwWindowHint( GLFW_CLIENT_API, GLFW_NO_API ); // Disable OpenGL Context
    glfwWindowHint( GLFW_RESIZABLE, GLFW_FALSE );   // Disable Resize
    m_window = glfwCreateWindow( WIDTH, HEIGHT, "Cicada-Engine", nullptr, nullptr );
}

//==========================================================================================================================================================
//==========================================================================================================================================================
void CicadaEngine::initVulkan() {
    m_cicaInstance       = cicaInstance();
    m_cicaDebugMessenger = cicaDebugMessenger( m_cicaInstance ); // Software Version Verification
    m_cicaPhysicalDevice = cicaPhysicalDevice( m_cicaInstance ); // Hardware Version Verification
}

//==========================================================================================================================================================
//==========================================================================================================================================================
void CicadaEngine::mainLoop() {
    while ( !glfwWindowShouldClose( m_window ) ) {
        glfwPollEvents();
    }
}

//==========================================================================================================================================================
//==========================================================================================================================================================
void CicadaEngine::cleanup() {
    glfwDestroyWindow( m_window );
    glfwTerminate();
}